#' Fit a BBT model by running MCMC on a wintable
#'
#' @inheritParams bbtcomp
#' @param tablex A wintable
#' @param use_davidson Whether to use the Davidson model to deal with ties
#' @param ... Further parameters to the MCMC (cmdstanr model and fit)
#'
#' @return A fitted BBT model
#' @export
#'
#' @section CmdStan setup:
#' Installing bbtcomp installs the \code{cmdstanr} R package, but it
#' cannot install or verify CmdStan itself (the compiled Stan backend).
#' If CmdStan cannot be found, this function stops with setup
#' instructions (see \code{\link{check_setup}}) instead of a deep
#' cmdstanr error.
#'
#' @examples
#' \donttest{
#' ss <- ll[1:80, 1:6] # first 20 data sets and 5 algorithms
#'
#' wintable <- make_wintable(ss, lrope = FALSE)
#'
#' options(mc.cores = parallel::detectCores(logical = FALSE))
#'
#' m1 <- mcmcbbt(wintable, hyper_prior = 0, scale = 0.5,
#'      use_davidson = TRUE)
#'
#' m2 <- mcmcbbt(wintable, iter_sampling = 2000, seed = 1234)
#' }
mcmcbbt <- function(tablex,
                    hyper_prior = 0,
                    scale = 0.5,
                    use_davidson = FALSE,
                    ...) {

  .ensure_cmdstan()

  pairs <- tablex$table
  N <- nrow(pairs)
  K <- length(tablex$alg_names)
  data <- list(K = K,
               N = N,
               player1 = as.integer(pairs$pi),
               player2 = as.integer(pairs$pj),
               win1 = pairs$win1,
               win2 = pairs$win2)

  #Directory for stan compiled file and csv files
  outdir <- getOption("bbtcomp.dir",default = tempdir())
  dir.create(outdir, showWarnings = FALSE)


  data <- c(data,
            list(use_davidson = as.integer(use_davidson),
                   hyp = hyper_prior,
                   scale = scale,
                   ties = pairs$ties))
  model_file <-
      system.file("stan",
                  "bbt-full.stan",
                  package = "bbtcomp",
                  mustWork = TRUE)


  model <- cmdstanr::cmdstan_model(model_file, dir = outdir)
  fit <- model$sample(data = data,
                      refresh = 0,
                      output_dir = outdir,
                      ...)

  ## need this to read the .csv files generated by the model$sample() call
  diagnostics <- fit$sampler_diagnostics()
  draws <- fit$draws()


  return(list(model = fit,
              davidson = as.logical(use_davidson),
              wintable = tablex))
}
